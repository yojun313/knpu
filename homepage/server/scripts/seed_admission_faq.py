def seed_categories(dry_run: bool):
    existing = admission_faq_categories_db.count_documents({})
    if existing:
        print(f"admission-faq-categories 에 이미 {existing}건이 있어 카테고리 시딩을 건너뜁니다.")
        return

    # FAQ_ITEMS 에 등장하는 순서대로 카테고리 순번(10, 20, …)을 매긴다.
    names = []
    for category, _, _ in FAQ_ITEMS:
        if category and category not in names:
            names.append(category)

    docs = [
        {"uid": str(uuid.uuid4()), "name": name, "order": (i + 1) * 10}
        for i, name in enumerate(names)
    ]
    print(f"카테고리 삽입 대상 {len(docs)}건:")
    for d in docs:
        print(f"  [{d['order']:>3}] {d['name']}")

    if dry_run:
        print("--dry-run: 카테고리 삽입 생략\n")
        return

    admission_faq_categories_db.insert_many(docs)
    print(f"카테고리 시딩 완료: {len(docs)}건 삽입됨.\n")


def seed(dry_run: bool):
    seed_categories(dry_run)

    existing = admission_faq_db.count_documents({})
    if existing:
        print(f"admission-faq 컬렉션에 이미 {existing}건이 있어 시딩을 건너뜁니다.")
        return

    docs = [
        {
            "uid": str(uuid.uuid4()),
            "category": category,
            "question": question,
            "answer": answer,
            "order": (i + 1) * 10,
        }
        for i, (category, question, answer) in enumerate(FAQ_ITEMS)
    ]

    print(f"삽입 대상 {len(docs)}건:")
    for d in docs:
        print(f"  [{d['order']:>3}] {d['category']} — {d['question'][:40]}...")

    if dry_run:
        print("\n--dry-run 모드: 실제 삽입은 수행하지 않았습니다.")
        return

    admission_faq_db.insert_many(docs)
    print(f"\n시딩 완료: {len(docs)}건 삽입됨.")


